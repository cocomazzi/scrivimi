const assert = require('node:assert/strict');
const {keys, merge, equal, decode} = require('./cloud-sync-core.js');
const [words, notes, images] = keys;
const payload = (n = {}, w = [], i = {}) => ({[words]: JSON.stringify(w), [notes]: JSON.stringify(n), [images]: JSON.stringify(i)});
const base = payload({'0': ['prima', 'seconda']}, [['ciao', 'hallo']]);
const local = payload({'0': ['modifica A', 'seconda']}, [['ciao', 'hallo']]);
const remote = payload({'0': ['prima', 'modifica B']}, [['ciao', 'hallo']]);
assert.deepEqual(JSON.parse(merge(base, local, remote).payload[notes])['0'], ['modifica A', 'modifica B']);
assert.equal(merge(base, local, payload({'0': ['altra modifica', 'seconda']}, [['ciao', 'hallo']])).conflicts.length, 1);
assert(equal(decode(merge({}, {}, remote).payload), decode(remote)), 'fresh device must load cloud, never erase it');
assert(equal(decode(merge({}, local, {}).payload), decode(local)), 'first account must retain guest work');
assert.equal(merge(base, payload({}, []), remote).conflicts.length, 1, 'deleting remotely edited answer needs a choice');
assert.equal(merge(base, payload({'0':['prima','seconda']}, [['A','a']]), payload({'0':['prima','seconda']}, [['B','b']])).conflicts.length, 1);
assert.deepEqual(JSON.parse(merge(base, local, {...remote, future: 'preserve', 'parliamo-session-v1': '{}'}).payload[notes])['0'], ['modifica A', 'modifica B']);
assert.equal(merge(base, local, {...remote, future: 'preserve'}).payload.future, 'preserve');
assert(equal({b:2,a:1},{a:1,b:2}));
assert.throws(()=>decode({[notes]: 'not json'}));
assert.throws(()=>decode({[notes]: '{"0":{"bad":"shape"}}'}));
assert.throws(()=>decode({[words]: '[["incomplete"]]'}));
assert(equal(decode(merge(base, base, payload({}, [])).payload), decode(payload({}, []))), 'remote deletion propagates');
console.log('PASS: independent edits, same-answer conflicts, guest migration, fresh device, deletions, vocabulary conflicts, invalid payloads, unknown fields.');
